import {readFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=new URL('./',import.meta.url);
const html=await readFile(new URL('index.html',root),'utf8');
const js=await readFile(new URL('app.js',root),'utf8');
const css=await readFile(new URL('app.css',root),'utf8');
const {markets}=JSON.parse(await readFile(new URL('../data/markets.json',root),'utf8'));
assert.equal(markets.length,100);
assert.equal(new Set(markets.map(m=>m.id)).size,100);
assert(markets.every(m=>Array.isArray(m.odds)&&Array.isArray(m.outcomes)&&m.id&&m.marketName));
for(const [,path] of html.matchAll(/(?:src|href)="(\.\/[^\"]+)"/g))await readFile(new URL(path,root));
assert(!/<(?:script|link)[^>]+(?:src|href)="https?:/.test(html),'No remote executable assets');
assert(!/\bimport\s.*https?:/.test(js),'No remote imports');
assert(js.includes("fetch('../data/markets.json')"));
assert(css.includes('prefers-reduced-motion'));
assert.equal(css.split('{').length,css.split('}').length,'Balanced CSS blocks');
const parsed=spawnSync(process.execPath,['--check',new URL('app.js',root).pathname],{encoding:'utf8'});
assert.equal(parsed.status,0,parsed.stderr);
console.log('PASS: 100 unique real markets; local assets; no CDN; module syntax; CSS structure; reduced-motion rule.');
console.log('Static checks only: browser layout and interaction checks were not run.');
